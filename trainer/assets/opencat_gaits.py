def frame_to_opencat_deg(frame: list[int]) -> dict[int, float]:
    """One 8-column gait row -> {opencat_index: firmware_degrees}."""
    return {idx: float(frame[col]) for (col, idx, _act, _sign, _rest) in GAIT_COL_MAP}


def frame_to_mjcf_ctrl(frame: list[int]) -> list[float]:
    """One 8-column gait row -> MJCF ctrl vector (actuator order rf,lf,rr,lr; sh,kn)."""
    ctrl = [0.0] * 8
    for (col, _idx, act, sign, rest) in GAIT_COL_MAP:
        ctrl[act] = (frame[col] - rest) * sign * math.pi / 180.0
    return ctrl


def gait_ctrl_frames(name: str) -> list[list[float]]:
    if name not in GAITS:
        raise KeyError(f"unknown gait {name!r}; available: {sorted(GAITS)}")
    return [frame_to_mjcf_ctrl(f) for f in GAITS[name]]


def pose_ctrl(name: str) -> list[float]:
    if name not in POSES:
        raise KeyError(f"unknown pose {name!r}; available: {sorted(POSES)}")
    return frame_to_mjcf_ctrl(POSES[name][8:16])


